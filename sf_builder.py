#!/usr/bin/env python3
# sf_builder.py -- S-function builder for lwrap (Link-theory edition)
#
# The Simulink S-Function Builder takes a block declaration
# (inputs / outputs / parameters / states) plus processing code and
# generates the wrapper (the S-function) that glues the block into
# Simulink.  Here the "block" is a POLE of Link theory: the pole
# declares its interface (argv / env / fds in, stdout / exit code
# out, parameters such as rootfs / uid / workdir), and the builder
# generates the EDGES -- the named, ordered syscall steps that glue
# the outside world to the inside of the room -- and emits a static,
# -nostdlib ELF called "lwrap" (bwrap rewritten in edge notation).
#
# Input : a pole spec (JSON).  See spec_lwrap.json.
# Output: lwrap_gen.c  (generated C, raw syscalls only)
#         lwrap        (static ELF, no interpreter, no libc)
#
# The generated program is NOT hand-written lwrap: every syscall
# step in it is emitted from one entry of the spec's "edges" list,
# and the order constraints between edges are checked here, in the
# builder, before any C is produced.

import json
import subprocess
import sys
import os

# ------------------------------------------------------------------
# Edge catalogue: name -> (phase, generator key)
# Phase order is the only legal order; the builder rejects a spec
# whose edges are not in phase order.  "exec_cmd" must be last.
# ------------------------------------------------------------------
EDGE_PHASES = {
    "unshare_user":       10,   # unshare(CLONE_NEWUSER)
    "deny_setgroups":     20,   # write "deny" -> /proc/self/setgroups
    "write_uid_map":      30,   # write "inner outer 1" -> /proc/self/uid_map
    "write_gid_map":      40,   # same for gid_map
    "unshare_mount":      50,   # unshare(CLONE_NEWNS)
    "unshare_net":        55,   # unshare(CLONE_NEWNET) + loopback up (optional)
    "unshare_pid":        60,   # unshare(CLONE_NEWPID) + fork (optional edge)
    "mount_private_root": 70,   # mount(NULL,"/",MS_REC|MS_PRIVATE)
    "bind_rootfs":        80,   # mount(rootfs, rootfs, MS_BIND|MS_REC)
    "mount_proc":         90,   # mount("proc", rootfs/proc)   (optional edge)
    "bind_device":        95,   # bind host device nodes into rootfs/dev (optional)
    "chroot_rootfs":     100,   # chroot(rootfs)
    "chdir_work":        110,   # chdir(workdir)
    "pin_cpus":          115,   # sched_setaffinity from --cpus (optional edge)
    "exec_cmd":          120,   # execve(cmd) with /bin,/usr/bin search
}

REQUIRED_EDGES = ["exec_cmd"]


def fail(msg):
    sys.stderr.write("sf_builder: %s\n" % msg)
    sys.exit(1)


def validate(spec):
    pole = spec.get("pole")
    if not pole or "name" not in pole:
        fail("spec has no pole.name")
    edges = spec.get("edges")
    if not edges:
        fail("spec has no edges list")
    names = []
    for e in edges:
        n = e["name"]
        if n not in EDGE_PHASES:
            fail("unknown edge %r (not in the edge catalogue)" % n)
        names.append(n)
    for r in REQUIRED_EDGES:
        if r not in names:
            fail("required edge %r missing from spec" % r)
    phases = [EDGE_PHASES[n] for n in names]
    if phases != sorted(phases):
        fail("edges are not in phase order: %s" % ", ".join(names))
    if names[-1] != "exec_cmd":
        fail("exec_cmd must be the last edge")
    # dependency checks (the glue rules of the room)
    if "write_uid_map" in names and "unshare_user" not in names:
        fail("write_uid_map requires unshare_user before it")
    if "write_gid_map" in names and "deny_setgroups" not in names:
        fail("write_gid_map requires deny_setgroups before it")
    if "mount_proc" in names and "bind_rootfs" not in names:
        fail("mount_proc requires bind_rootfs before it")
    if "chroot_rootfs" in names and "bind_rootfs" not in names:
        fail("chroot_rootfs requires bind_rootfs before it")
    if "bind_device" in names and "bind_rootfs" not in names:
        fail("bind_device requires bind_rootfs before it")
    if "unshare_net" in names and "unshare_user" not in names:
        fail("unshare_net requires unshare_user before it "
             "(an unprivileged net namespace lives in a user ns)")
    return names


