C_STEP["unshare_user"] = r"""
/* Edge unshare_user, with the measured constraint of this cell:
 * a process may NOT write its own uid_map/gid_map here (EPERM,
 * verified against util-linux unshare as well).  So, like bwrap,
 * the builder generates a parent/child pair: the child unshares,
 * the PARENT performs the map edges (deny_setgroups, write_uid_map,
 * write_gid_map -- emitted as parent_* helpers by those edges, in
 * spec order), then releases the child and propagates its exit. */
static void write_file_for(const char *edge, i64 pid, const char *leaf,
                           const char *data){
    char path[128], pb[24];
    scat(path, "/proc/", sitoa(pb, (long)pid));
    { u64 n = slen(path); scat(path+n, "/", leaf); }
    write_file(edge, path, data);
}
%(map_helpers)s
static void step_unshare_user(void){
    int ready[2], go[2];   /* pipe2 writes 32-bit fds; i64 here corrupts [1] */
    edge_die("unshare_user", sc2(SYS_pipe2, (i64)ready, 0));
    edge_die("unshare_user", sc2(SYS_pipe2, (i64)go, 0));
    i64 pid = sc1(SYS_fork, 0);
    edge_die("unshare_user", pid);
    if(pid == 0){
        sc1(SYS_close, ready[0]); sc1(SYS_close, go[1]);
        edge_die("unshare_user", sc1(SYS_unshare, CLONE_NEWUSER));
        char b = 'r';
        sc3(SYS_write, ready[1], (i64)&b, 1);      /* tell parent: ns exists */
        sc3(SYS_read, go[0], (i64)&b, 1);          /* wait for the maps */
        return;
    }
    sc1(SYS_close, ready[1]); sc1(SYS_close, go[0]);
    char b;
    sc3(SYS_read, ready[0], (i64)&b, 1);
%(parent_map_calls)s
    sc3(SYS_write, go[1], (i64)"g", 1);
    i64 st = 0;
    sc5(SYS_wait4, pid, (i64)&st, 0, 0, 0);
    if((st & 0x7f) == 0) sc1(SYS_exit, (st >> 8) & 0xff);
    sc1(SYS_exit, 128 + (st & 0x7f));
}
"""

