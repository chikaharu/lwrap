def gen_c(spec):
    names = validate(spec)
    params = spec.get("params", {})
    pole = spec["pole"]
    subs = {
        "pole_name": pole["name"],
        "spec_name": spec.get("spec_name", "<inline>"),
        "edge_names": ", ".join(names),
        "p_rootfs": params.get("rootfs", "/"),
        "p_workdir": params.get("workdir", "/"),
        "p_uid": int(params.get("uid", 0)),
        "p_gid": int(params.get("gid", 0)),
        "p_proc": 1 if params.get("proc", False) else 0,
        "p_pid": 1 if params.get("pid", False) else 0,
        "p_net": 1 if params.get("net", False) else 0,
        "p_cpus": str(params.get("cpus", "")).replace('"', ""),
        "p_devices": "".join(
            '"%s", ' % str(d).replace('"', "")
            for d in params.get("devices", [])),
    }
    header = C_HEADER
    for k, v in subs.items():
        header = header.replace("%%(%s)s" % k, str(v))
    out = [header]
    for n in names:
        chunk = C_STEP[n]
        if n == "unshare_user":
            helpers = "".join(MAP_HELPERS[m] for m in names
                              if m in FOLDED_INTO_UNSHARE_USER)
            pcalls = "".join("    parent_%s(pid);\n" % m for m in names
                             if m in FOLDED_INTO_UNSHARE_USER)
            chunk = chunk.replace("%(map_helpers)s", helpers)
            chunk = chunk.replace("%(parent_map_calls)s", pcalls)
        out.append(chunk)
    call_lines = []
    for n in names:
        if n in FOLDED_INTO_UNSHARE_USER:
            call_lines.append(
                "    /* edge %s: run by the parent inside step_unshare_user */"
                % n)
        else:
            call_lines.append("    step_%s();" % n)
    calls = "\n".join(call_lines)
    out.append(C_MAIN.replace("%(step_calls)s", calls))
    return "".join(out)


def main(argv):
    if len(argv) < 2:
        fail("usage: sf_builder.py SPEC.json [--outdir DIR] [--no-build]")
    spec_path = argv[1]
    outdir = os.path.dirname(os.path.abspath(spec_path))
    build = True
    if "--outdir" in argv:
        outdir = argv[argv.index("--outdir") + 1]
    if "--no-build" in argv:
        build = False
    with open(spec_path) as f:
        spec = json.load(f)
    spec["spec_name"] = os.path.basename(spec_path)
    code = gen_c(spec)
    os.makedirs(outdir, exist_ok=True)
    cpath = os.path.join(outdir, "lwrap_gen.c")
    with open(cpath, "w") as f:
        f.write(code)
    print("sf_builder: pole %r -> %s (%d bytes of C)"
          % (spec["pole"]["name"], cpath, len(code)))
    print("sf_builder: edges: %s"
          % ", ".join(e["name"] for e in spec["edges"]))
    if build:
        elf = os.path.join(outdir, spec["pole"]["name"])
        cmd = ["gcc", "-nostdlib", "-static", "-Os", "-ffreestanding",
               "-fno-stack-protector", "-fno-pie", "-Wl,-e,_start",
               "-o", elf, cpath]
        print("sf_builder: build: %s" % " ".join(cmd))
        r = subprocess.run(cmd, capture_output=True, text=True)
        if r.returncode != 0:
            sys.stderr.write(r.stderr)
            fail("gcc failed")
        print("sf_builder: built %s (%d bytes)"
              % (elf, os.path.getsize(elf)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
